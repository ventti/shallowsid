import { test } from "node:test";
import assert from "node:assert/strict";

globalThis.self = globalThis;
globalThis.PixelAvatar = (await import("../js/pixelavatar.js")).default;
const { connectMediaSession } = await import("../js/player/media-session.js");

test("system controls reach the player and artwork publishes atomically for the latest track", async (t) => {
  const originals = new Map(["navigator", "MediaMetadata", "Image", "document"].map((key) => [key, Object.getOwnPropertyDescriptor(globalThis, key)]));
  t.after(() => {
    for (const [key, descriptor] of originals) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor);
      else delete globalThis[key];
    }
  });
  let now = 10000;
  t.mock.method(performance, "now", () => now);
  const positions = [];
  const handlers = {};
  const oldMetadata = { title: "Old", artwork: [{ src: "old.png" }] };
  const ms = { setPositionState: (state) => positions.push(state), metadata: oldMetadata, setActionHandler(action, handler) { handlers[action] = handler; } };
  Object.defineProperty(globalThis, "navigator", { configurable: true, value: { mediaSession: ms } });
  globalThis.MediaMetadata = class { constructor(info) { Object.assign(this, info); } };
  const images = [];
  globalThis.Image = class { constructor() { images.push(this); } };
  globalThis.document = { createElement: () => ({ getContext: () => ({ drawImage() {} }), toDataURL: () => "data:image/png;base64,cover" }) };
  const calls = [];
  const player = new EventTarget();
  for (const action of ["play", "pause", "next", "previous", "seek"]) player[action] = (...args) => calls.push([action, ...args]);
  player.position = 30;
  connectMediaSession(player);
  handlers.play();
  handlers.pause();
  handlers.nexttrack();
  handlers.previoustrack();
  handlers.seekforward({});
  handlers.seekbackward({ seekOffset: 5 });
  handlers.seekto({ seekTime: 70 });
  assert.deepEqual(calls, [["play"], ["pause"], ["next"], ["previous"], ["seek", 40], ["seek", 25], ["seek", 70]]);
  const time = (position, duration) => player.dispatchEvent(new CustomEvent("time", { detail: { position, duration } }));
  const track = (title) => {
    player.position = 0;
    player.duration = 200;
    player.dispatchEvent(new CustomEvent("track", { detail: { item: { title, path: title, author: "Composer", song: 1 } } }));
  };
  time(30, 180);
  now += 100;
  track("First");
  track("Second");
  assert.deepEqual(positions.map((state) => state.position), [30, 0, 0], "each track resets position even inside the throttle window");
  assert.equal(ms.metadata, oldMetadata);
  player.position = 2;
  images[1].onload();
  await Promise.resolve();
  assert.equal(ms.metadata.title, "Second");
  assert.equal(ms.metadata.artwork.length, 1);
  assert.equal(positions.at(-1).position, 2, "new metadata republishes the current track position");
  const positionCount = positions.length;
  images[0].onload();
  await Promise.resolve();
  assert.equal(ms.metadata.title, "Second");
  assert.equal(positions.length, positionCount, "stale artwork cannot overwrite the current position");
  track("Broken cover");
  images[2].onerror(new Error("image failed"));
  await Promise.resolve();
  assert.equal(ms.metadata.title, "Broken cover");
  const before = positions.length;
  time(0.1, 200);
  assert.equal(positions.length, before, "ordinary ticks remain throttled");
  now += 1100;
  time(3, NaN);
  time(3, Infinity);
  time(3, 0);
  assert.equal(positions.length, before, "invalid durations are not published");
  time(3, 200);
  assert.equal(positions.at(-1).position, 3);
  const state = (value, position) => {
    player.position = position;
    player.dispatchEvent(new CustomEvent("state", { detail: { state: value } }));
  };
  state("paused", 3.4);
  assert.equal(ms.playbackState, "paused");
  assert.equal(positions.at(-1).position, 3.4, "pause updates the exact position without waiting for a tick");
  state("playing", 3.4);
  assert.equal(ms.playbackState, "playing");
  assert.equal(positions.at(-1).position, 3.4);
  time(0, 200);
  assert.equal(positions.at(-1).position, 0, "restart bypasses the throttle while paused or playing");
  time(20, 200);
  assert.equal(positions.at(-1).position, 20, "forward seeks bypass the throttle too");
  state("idle", 0);
  assert.equal(ms.playbackState, "none");
});
